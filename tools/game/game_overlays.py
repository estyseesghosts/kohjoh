#!/usr/bin/env python3
"""Give each game overlay its own data sections, and write the overlay table.

Usage:
    python tools/game_overlays.py --lsf build/upstream/main.lsf \\
        --upstream build/upstream --objdir <game build dir> \\
        --objcopy arm-none-eabi-objcopy --output <...>/overlay_table.c
    python tools/game_overlays.py --lsf build/upstream/main.lsf \\
        --ids-output <...>/overlay_ids.ld --header <...>/overlay_ids.h

On the DS, an overlay is loaded from the cartridge each time it's needed,
which resets its data: its initialised variables get their initial values
back and its zero-initialised ones are cleared. The port links every
overlay into the program, so it has to do that reset itself
(3ds_port/nitro/src/port_overlay.c). For that it needs each overlay's data
in one place.

The linker spec (main.lsf) says which objects make up each overlay. This
renames those objects' data sections (.data, .data.*, .bss, .bss.*) to
ovl_data_<overlay> and ovl_bss_<overlay>, so the linker gathers them and
defines __start_/__stop_ symbols around them, and writes a C table of those
bounds in overlay-ID order (the order of the Overlay entries in main.lsf),
for the program to pass to NitroPort_SetOverlays (see render_table for why
the program links it last). Renaming is idempotent.

Static initializers: an overlay's NitroStaticInit functions (the port's
NitroSDK patch for GCC, cf. pokeplatinum-3ds 0027) ran each time the DS
loaded it. Each one leaves a pointer to itself in section .sinit; this
renames that to ovl_sinit_<overlay> too, so each overlay gets a table of
its own, and the overlay table records its bounds.

C++ static constructors: src/lobby/*.cpp (overlay OVY_45) is built with
-fno-exceptions -fno-rtti, under which GCC emits global constructors into
.init_array (older toolchains: .ctors), not .sinit. Those sections are
renamed into ovl_sinit_<overlay> as well, so the constructors run on
FS_StartOverlay when port_overlay.c iterates sinit_init..sinit_init_end,
and do NOT run at program start (nothing named .init_array/.ctors is left
for the C runtime to call).

Overlay regions: an overlay placed "After" the ITCM or DTCM autoload was
loaded into that memory on the DS; the game's overlay manager keeps a list
of loaded overlays per region, so the table records it. All 129 HGSS
overlays chain back to main (MAIN); the After/Address logic is kept
general.

Overlay IDs: FS_OVERLAY_ID(name) is the overlay's position in the linker
spec's list of "Overlay <name>" entries, from 0. --ids-output writes a GNU
ld script defining SDK_OVERLAY_<name>_ID at that number (as Nintendo's
linker did), and --header writes SDK_PORT_OVERLAY_ID_<name> constants (an
address doesn't fit the game's 32-bit overlay-ID fields on a 64-bit PC; a
constant does on every machine). The game is compiled with the header
(-include).
"""

from __future__ import annotations

import argparse
import re
import struct
import subprocess
import sys
from pathlib import Path

REGIONS = {"main": "MAIN", "ITCM": "ITCM", "DTCM": "DTCM"}

# Object names in main.lsf are checkout-relative paths (src/foo.o,
# asm/bar.o, lib/.../baz.o), unlike pret/pokeplatinum's Meson-mangled names,
# so overlay_objects() maps them to the port's build directory directly.
# A few objects have no checkout source: lib/dsprot's *_encrypted.o /
# *_encoded.o / *_decoder.o are generated by lib/dsprot's own Makefile at
# build time. They still map to objdir paths; object_source() reports them
# as having no source.


# --------------------------------------------------------------- main.lsf

def parse_lsf(text: str) -> dict:
    """The linker spec's Static block, Autoload blocks and Overlay entries.

    Returns {"static": block or None, "autoloads": [...], "overlays": [...]},
    each block a dict with kind, name, after, address, objects ([{"path",
    "section"}]; section is the parenthesised suffix such as "(.itcm)" or
    None) and libraries. Overlays are in declaration order: index 0..128 is
    the overlay ID.
    """
    static = None
    autoloads: list[dict] = []
    overlays: list[dict] = []
    current = None
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        m = re.match(r"^(Static|Autoload|Overlay)\s+([A-Za-z_][A-Za-z0-9_]*)$", line)
        if m:
            current = {"kind": m.group(1), "name": m.group(2), "after": None,
                       "address": None, "objects": [], "libraries": []}
            if m.group(1) == "Overlay":
                overlays.append(current)
            elif m.group(1) == "Autoload":
                autoloads.append(current)
            else:
                if static is not None:
                    raise ValueError("two Static blocks in the linker spec")
                static = current
            continue
        if current is None or line in ("{", "}"):
            continue
        words = line.split()
        if words[0] == "After":
            current["after"] = words[1]
        elif words[0] == "Address":
            current["address"] = int(words[1], 0)
        elif words[0] == "Object":
            section = None
            if len(words) > 2:
                sm = re.fullmatch(r"\(([^)]*)\)", words[2])
                if not sm:
                    raise ValueError(f"bad Object line: {raw.strip()!r}")
                section = sm.group(1)
            current["objects"].append({"path": words[1], "section": section})
        elif words[0] == "Library":
            current["libraries"].append(words[1])
    if not overlays:
        raise ValueError("no Overlay entries in the linker spec")
    names = [o["name"] for o in overlays]
    if len(set(names)) != len(names):
        raise ValueError("an overlay name appears twice")
    return {"static": static, "autoloads": autoloads, "overlays": overlays}


def overlay_names(lsf_text: str) -> list[str]:
    """Overlay names in declaration order (index 0..N-1 is the overlay ID)."""
    return [o["name"] for o in parse_lsf(lsf_text)["overlays"]]


def region(overlays: list[dict], name: str) -> str:
    """MAIN, ITCM or DTCM: where the overlay was loaded on the DS."""
    by_name = {o["name"]: o for o in overlays}
    seen = set()
    while name not in REGIONS:
        if name in seen or name not in by_name:
            raise ValueError(f"can't place overlay {name!r}")
        seen.add(name)
        entry = by_name[name]
        if entry["address"] is not None:
            address = entry["address"]
            if 0x01FF8000 <= address < 0x02000000:
                return "ITCM"
            if 0x027E0000 <= address < 0x027E4000:
                return "DTCM"
            return "MAIN"
        if entry["after"] is None:
            raise ValueError(f"overlay {name!r} has no After or Address")
        name = entry["after"]
    return REGIONS[name]


# ------------------------------------------------------- objects of each one

def object_source(upstream: Path, objpath: str) -> str | None:
    """Checkout-relative source for an object path, or None if generated.

    src/foo.o comes from src/foo.c or src/foo.cpp (OVY_45's src/lobby files
    are a mix of both, as are src/to91_msl_*.cpp beside their .c
    neighbours); asm/ and lib/ objects come from the same path with .s,
    then .c/.cpp. lib/dsprot's encrypted/encoded/decoder objects are
    generated at build time and report None.
    """
    if not objpath.endswith(".o"):
        raise ValueError(f"not an object path: {objpath!r}")
    base = objpath[:-2]
    if objpath.startswith("src/"):
        for ext in (".c", ".cpp"):
            if (upstream / (base + ext)).is_file():
                return base + ext
        return None
    for ext in (".s", ".c", ".cpp"):
        if (upstream / (base + ext)).is_file():
            return base + ext
    return None


def overlay_objects(upstream: Path, overlays: list[dict], objdir: Path) -> dict[str, list[Path]]:
    """Each overlay's object files in the port's build.

    Object names are already checkout-relative paths, so this is objdir
    joined to each entry. Entries whose source is build-generated (dsprot)
    map the same way; objects missing from this build are skipped later, at
    rename time, with a count (see main).
    """
    del upstream  # mapping needs no source lookup; object_source() is for reports
    result: dict[str, list[Path]] = {}
    for o in overlays:
        files = []
        for entry in o["objects"]:
            if not entry["path"].endswith(".o"):
                raise ValueError(f"overlay {o['name']}: {entry['path']} is not an object")
            files.append(objdir / entry["path"])
        for library in o["libraries"]:
            raise ValueError(f"overlay {o['name']}: unexpected Library {library!r} "
                             f"(HGSS main.lsf uses Object entries only)")
        result[o["name"]] = files
    return result


# ------------------------------------------------------------- ELF sections

def sections(path: Path) -> list[tuple[str, int]]:
    """An ELF object's sections, as (name, size) (32- or 64-bit,
    little-endian)."""
    data = path.read_bytes()
    if data[:4] != b"\x7fELF" or data[5] != 1:
        raise ValueError(f"{path}: not a little-endian ELF file")
    if data[4] == 1:
        shoff, = struct.unpack_from("<I", data, 0x20)
        shentsize, shnum, shstrndx = struct.unpack_from("<HHH", data, 0x2E)

        def header(i):
            name, _, _, _, offset, size = struct.unpack_from("<IIIIII", data, shoff + i * shentsize)
            return name, offset, size
    else:
        shoff, = struct.unpack_from("<Q", data, 0x28)
        shentsize, shnum, shstrndx = struct.unpack_from("<HHH", data, 0x3A)

        def header(i):
            name, _, _, _, offset, size = struct.unpack_from("<IIQQQQ", data, shoff + i * shentsize)
            return name, offset, size
    _, stroff, strsize = header(shstrndx)
    strtab = data[stroff:stroff + strsize]
    result = []
    for i in range(shnum):
        name, _, size = header(i)
        end = strtab.index(b"\0", name)
        result.append((strtab[name:end].decode("ascii"), size))
    return result


def section_names(path: Path) -> list[str]:
    return [name for name, _ in sections(path)]


def data_kind(section: str) -> str | None:
    """'data' or 'bss' for a writable data section the reset must cover."""
    if section == ".data" or (section.startswith(".data.") and not section.startswith(".data.rel.ro")):
        return "data"
    if section == ".bss" or section.startswith(".bss."):
        return "bss"
    return None


def sinit_kind(section: str) -> str | None:
    """'sinit' for a static-initializer section the overlay load must run.

    NitroStaticInit pointers live in .sinit; GCC's C++ constructors (with
    -fno-exceptions -fno-rtti, as src/lobby/*.cpp builds) live in
    .init_array (or .ctors on older toolchains), with -ffunction-sections
    suffixes possible for both.
    """
    if section == ".sinit" or section.startswith(".sinit."):
        return "sinit"
    if section == ".init_array" or section.startswith(".init_array."):
        return "sinit"
    if section == ".ctors" or section.startswith(".ctors."):
        return "sinit"
    return None


def rename_sections(path: Path, overlay: str, objcopy: str) -> set[str]:
    """Rename one object's data sections, and its static initializers'
    sections, for `overlay`. Returns the kinds ('data', 'bss', 'sinit') the
    object holds for it (in sections renamed now or before; empty sections
    don't count)."""
    renames = []
    kinds = set()
    for name, size in sections(path):
        kind = sinit_kind(name) or data_kind(name)
        if kind is not None:
            renames += ["--rename-section", f"{name}=ovl_{kind}_{overlay}"]
        elif name == f"ovl_data_{overlay}":
            kind = "data"
        elif name == f"ovl_bss_{overlay}":
            kind = "bss"
        elif name == f"ovl_sinit_{overlay}":
            kind = "sinit"
        if kind is not None and size > 0:
            kinds.add(kind)
    if renames:
        subprocess.run([objcopy, *renames, str(path)], check=True)
    return kinds


# ------------------------------------------------------------------ table

def render_table(overlays: list[dict]) -> str:
    """The overlay table, in C. It also ends each overlay's two data sections
    with 4 bytes of its own: so every overlay has both (the linker defines
    the __start_/__stop_ symbols only for sections that exist), and each
    ends on a 4-byte boundary (3dsxtool requires the program's data to). The
    program links this object after the game's, which puts those bytes
    last. Each overlay's table of static initializers ends with a null
    pointer, for the same reason (FS_StartOverlay skips null entries)."""
    lines = [
        "/* Generated by tools/game_overlays.py from main.lsf: every overlay, in",
        " * overlay-ID order, with the bounds of its data and of its static",
        " * initializers. Passed to NitroPort_SetOverlays by the program; linked",
        " * after the game's objects. */",
        "",
        "#include <nitro_port.h>",
        "",
    ]
    for o in overlays:
        name = o["name"]
        lines.append(f'__asm__(".section ovl_data_{name},\\"aw\\",%progbits\\n\\t.balign 4\\n'
                     f'\\t.space 4\\n\\t.previous\\n"'
                     f'        ".section ovl_bss_{name},\\"aw\\",%nobits\\n\\t.balign 4\\n'
                     f'\\t.space 4\\n\\t.previous\\n");')
        lines.append(f"extern u8 __start_ovl_data_{name}[], __stop_ovl_data_{name}[];")
        lines.append(f"extern u8 __start_ovl_bss_{name}[], __stop_ovl_bss_{name}[];")
        lines.append(f'__attribute__((section("ovl_sinit_{name}"), used)) '
                     f"static void (*ovl_sinit_end_{name})(void) = 0;")
        lines.append(f"extern void (*__start_ovl_sinit_{name}[])(void), "
                     f"(*__stop_ovl_sinit_{name}[])(void);")
    lines += ["", "const NitroPortOverlay gHeartgoldOverlays[] = {"]
    for index, o in enumerate(overlays):
        name = o["name"]
        lines.append(f"    /* {index:3} */ {{ \"{name}\", NITRO_PORT_OVERLAY_{region(overlays, name)}, "
                     f"__start_ovl_data_{name}, __stop_ovl_data_{name}, "
                     f"__start_ovl_bss_{name}, __stop_ovl_bss_{name}, "
                     f"__start_ovl_sinit_{name}, __stop_ovl_sinit_{name} }},")
    lines += ["};", "",
              "const u32 gHeartgoldOverlayCount = "
              "sizeof(gHeartgoldOverlays) / sizeof(gHeartgoldOverlays[0]);",
              ""]
    return "\n".join(lines)


# -------------------------------------------------------------- overlay IDs

def render_ids(names: list[str]) -> str:
    """GNU ld script: SDK_OVERLAY_<name>_ID at the overlay's number, as the
    DS linker made it."""
    lines = [
        "/* Generated by tools/game_overlays.py from main.lsf. */",
        "/* SDK_OVERLAY_<name>_ID is at the overlay's number, as the DS linker made it. */",
    ]
    lines += [f"SDK_OVERLAY_{name}_ID = {index};" for index, name in enumerate(names)]
    return "\n".join(lines) + "\n"


def render_ids_header(names: list[str]) -> str:
    """C header: each overlay's ID (FS_OVERLAY_ID(name) is
    SDK_PORT_OVERLAY_ID_<name> in the port's NitroSDK)."""
    lines = [
        "/* Generated by tools/game_overlays.py from main.lsf. */",
        "/* Each overlay's ID: its position in the linker spec. FS_OVERLAY_ID(name)",
        "   is SDK_PORT_OVERLAY_ID_<name> in the port's NitroSDK. */",
        "#ifndef PORT_GAME_OVERLAY_IDS_H",
        "#define PORT_GAME_OVERLAY_IDS_H",
        "",
        "/* The name lib/include/nitro/fs/overlay.h checks: with it, FS_OVERLAY_ID",
        "   is the enum constant below, not the address of a linker symbol. The",
        "   address form leaves absolute relocations 3dsxtool cannot package. */",
        "#define SDK_PORT_OVERLAY_IDS_H 1",
        "",
        "enum {",
    ]
    lines += [f"    SDK_PORT_OVERLAY_ID_{name} = {index}," for index, name in enumerate(names)]
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def write_if_changed(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.is_file() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--lsf", type=Path, required=True)
    parser.add_argument("--upstream", type=Path, required=True)
    parser.add_argument("--objdir", type=Path, required=True)
    parser.add_argument("--objcopy", default="objcopy")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--ids-output", type=Path, default=None,
                        help="also write the GNU ld overlay-ID script here")
    parser.add_argument("--header", type=Path, default=None,
                        help="also write the overlay-ID C header here")
    args = parser.parse_args()

    spec = parse_lsf(args.lsf.read_text(encoding="utf-8"))
    overlays = spec["overlays"]
    objects = overlay_objects(args.upstream, overlays, args.objdir)
    kinds: dict[str, set[str]] = {}
    count = missing = 0
    for name, files in objects.items():
        for path in files:
            if not path.is_file():
                missing += 1   # left out of this build
                continue
            kinds.setdefault(name, set()).update(rename_sections(path, name, args.objcopy))
            count += 1
    write_if_changed(args.output, render_table(overlays))
    if args.ids_output is not None:
        write_if_changed(args.ids_output, render_ids([o["name"] for o in overlays]))
    if args.header is not None:
        write_if_changed(args.header, render_ids_header([o["name"] for o in overlays]))
    note = f" ({missing} not in this build)" if missing else ""
    with_data = sum(1 for k in kinds.values() if k & {"data", "bss"})
    with_init = sum(1 for k in kinds.values() if "sinit" in k)
    print(f"  {len(overlays)} overlays ({with_data} with data, {with_init} with static "
          f"initializers), {count} objects{note}: sections grouped per overlay")


if __name__ == "__main__":
    main()
