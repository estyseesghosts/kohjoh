/*
 * The two DS BIOS sound tables and the ARM7 power-control pair the ARM7 sound
 * driver calls, for the port's virtual ARM7.
 *
 * HGSS's ARM7 driver reaches these through the BIOS (SVC_GetPitchTable /
 * SVC_GetVolumeTable are SWIs) and through its own power_manager_driver.c
 * (PMi_SetControl / PMi_ResetControl, which talk to the PM chip over the ARM7
 * SPI bus). Neither transport exists on the port: there is no BIOS and no
 * ARM7 SPI model. The tables are pure functions of their index, so they live
 * here; the PM control register is kept as a shadow word because only the
 * driver's sleep path reads it back (SND_BeginSleep / SND_EndSleep), and the
 * port's mixer does not sleep.
 *
 * Compiled by the Makefile's ARM7 rule (tools/hgss_nitro.py lists it in
 * ARM7_SOUND_SRCS), so every global here is renamed to N7_*, matching the
 * renamed references in the driver's own objects.
 *
 * Pitch: BIOS entry i of 768 is round(65536 * (2^(i/768) - 1)); the driver
 * adds 0x10000 back (sound_channel.c:264), giving the 1.0..2.0 rate ratio the
 * octave/exponent handling expects.
 *
 * Volume: NitroSDK 4.2's VolumeTable, the 724-entry DS system-ROM table
 * SVC_GetVolumeTable returns. Entry i is 0.1 dB steps from -72.3 dB at index 0
 * (silence) to 0 dB at index 723 (127); SND_CalcChannelVolume applies the
 * 4/2/1-bit channel-volume shift separately. The table is not a plain
 * 10^(dB/20) curve: its low range keeps non-zero values (1, 2, ...), which is
 * what keeps a slow attack audible. Rounding a smooth curve to the nearest
 * integer made those entries 0, so a sequence whose instrument has attack 0
 * (the slowest) mixed as silence; the vendored test_sound_sequence caught it.
 */

#include <math.h>

u32 SVC_GetPitchTable(int index)
{
    if (index <= 0) {
        return 0;
    }
    if (index >= 768) {
        index = 767;
    }
    return (u32)(65536.0 * (pow(2.0, (double)index / 768.0) - 1.0) + 0.5);
}

