#!/usr/bin/env python3
"""Compile and run the wide-art initialization regression test (cleanup task 4).

Run from the repository root: python tests/native/test_wideart.py
Set CC to a host C compiler if `gcc` is not on PATH.

The real wideart.c is compiled as its own translation unit with -Dmalloc=test_malloc;
the generated harness owns the blob and the fake citro3d/log functions. Each
failure case must leave the module empty and reloadable.
"""

import os
from pathlib import Path
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[2]

THREE_DS_H = """
#ifndef STUB_3DS_H
#define STUB_3DS_H
#include <stdint.h>
#endif
"""

CITRO3D_H = """
#ifndef STUB_CITRO3D_H
#define STUB_CITRO3D_H
#include <stdbool.h>
#include <stdint.h>
typedef uint16_t u16;
typedef enum { GPU_RGBA8 = 0, GPU_RGBA5551 = 1 } GPU_TEXCOLOR;
typedef enum { GPU_NEAREST = 0, GPU_LINEAR = 1 } GPU_TEXTURE_FILTER;
typedef enum { GPU_CLAMP_TO_EDGE = 0, GPU_REPEAT = 1 } GPU_WRAPMODE;
typedef struct C3D_Tex {
    void *data;
    u16 width, height;
    GPU_TEXCOLOR fmt;
} C3D_Tex;
bool C3D_TexInit(C3D_Tex *tex, u16 width, u16 height, GPU_TEXCOLOR fmt);
void C3D_TexDelete(C3D_Tex *tex);
void C3D_TexSetFilter(C3D_Tex *tex, GPU_TEXTURE_FILTER mag, GPU_TEXTURE_FILTER min);
void C3D_TexSetWrap(C3D_Tex *tex, GPU_WRAPMODE s, GPU_WRAPMODE t);
void C3D_TexFlush(C3D_Tex *tex);
#endif
"""

TEST_C = r"""
/* Generated by test_wideart.py; wideart.c is linked as a separate unit. */
#include <assert.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "graphics/g2d/wideart.h"

/* wideart.c declares these extern const. A separate translation unit keeps
 * the conflicting qualification out of the compiler's sight, so the harness
 * can rewrite the blob between cases. */
unsigned char wideart_bin[256];
unsigned int wideart_bin_size;

#define KEY1 0x5566778811223344ull
#define KEY2 0x12345678aabbccddull

static bool s_tex_init_fails;
static bool s_fail_table_malloc;
static unsigned s_tex_init_calls;
static unsigned s_delete_calls;

void kj_log(const char *fmt, ...) { (void)fmt; }

bool C3D_TexInit(C3D_Tex *tex, u16 width, u16 height, GPU_TEXCOLOR fmt) {
    ++s_tex_init_calls;
    if (s_tex_init_fails) {
        return false;
    }
    tex->data = malloc((size_t)width * height * 2u);
    if (tex->data == NULL) {
        return false;
    }
    tex->width = width;
    tex->height = height;
    tex->fmt = fmt;
    return true;
}

void C3D_TexDelete(C3D_Tex *tex) {
    ++s_delete_calls;
    free(tex->data);
    tex->data = NULL;
}

void C3D_TexSetFilter(C3D_Tex *tex, GPU_TEXTURE_FILTER mag, GPU_TEXTURE_FILTER min) {
    (void)tex;
    (void)mag;
    (void)min;
}

void C3D_TexSetWrap(C3D_Tex *tex, GPU_WRAPMODE s, GPU_WRAPMODE t) {
    (void)tex;
    (void)s;
    (void)t;
}

void C3D_TexFlush(C3D_Tex *tex) { (void)tex; }

void *test_malloc(size_t bytes) {
    if (s_fail_table_malloc) {
        return NULL;
    }
    return malloc(bytes);
}

static void put16(unsigned char *p, unsigned off, unsigned v) {
    p[off] = (unsigned char)(v & 0xffu);
    p[off + 1] = (unsigned char)((v >> 8) & 0xffu);
}

static void put32(unsigned char *p, unsigned off, uint32_t v) {
    for (unsigned i = 0; i < 4; ++i) {
        p[off + i] = (unsigned char)((v >> (8u * i)) & 0xffu);
    }
}

/* A valid two-picture blob: 16-byte header, two 32-byte records, 8x4 rows. */
static void valid_blob(void) {
    memset(wideart_bin, 0, sizeof(wideart_bin));
    memcpy(wideart_bin, "SJWA", 4);
    put16(wideart_bin, 4, 1);  /* version */
    put16(wideart_bin, 6, 2);  /* pictures */
    put16(wideart_bin, 8, 8);  /* texture width */
    put16(wideart_bin, 10, 8); /* texture height */
    put16(wideart_bin, 12, 4); /* picture rows */
    put32(wideart_bin, 16, 0x11223344u);
    put32(wideart_bin, 20, 0x55667788u);
    put32(wideart_bin, 48, 0xaabbccddu);
    put32(wideart_bin, 52, 0x12345678u);
    for (unsigned i = 16u + 2u * 32u; i < 16u + 2u * 32u + 8u * 4u * 2u; ++i) {
        wideart_bin[i] = (unsigned char)(i * 7u);
    }
    wideart_bin_size = 16u + 2u * 32u + 8u * 4u * 2u;
}

/* Search before checking the count: the old failure state had a positive
 * count with a NULL table, so this was a NULL dereference. */
static void failed_state_is_empty(void) {
    assert(!kj_wideart_init());
    assert(kj_wideart_find(KEY1) == NULL);
    assert(kj_wideart_find(KEY2) == NULL);
    assert(kj_wideart_count() == 0);
    assert(kj_wideart_texture() == NULL);
}

int main(void) {
    unsigned deletes;
    unsigned init_calls;

    valid_blob();
    assert(kj_wideart_init());
    assert(kj_wideart_count() == 2);
    const kj_wideart_pic *pic = kj_wideart_find(KEY1);
    assert(pic != NULL && pic->key == KEY1);
    pic = kj_wideart_find(KEY2);
    assert(pic != NULL && pic->key == KEY2);
    kj_wideart_exit();

    valid_blob();
    s_tex_init_fails = true;
    deletes = s_delete_calls;
    failed_state_is_empty();
    assert(s_delete_calls == deletes);
    s_tex_init_fails = false;
    assert(kj_wideart_init()); /* reload after error */
    kj_wideart_exit();

    valid_blob();
    wideart_bin_size = 16u + 32u; /* shorter than the two-record table */
    failed_state_is_empty();
    valid_blob(); /* reload after error */
    assert(kj_wideart_init());
    kj_wideart_exit();

    valid_blob();
    put16(wideart_bin, 8, 300); /* not a power of two */
    failed_state_is_empty();
    valid_blob(); /* reload after error */
    assert(kj_wideart_init());
    kj_wideart_exit();

    valid_blob();
    s_fail_table_malloc = true;
    deletes = s_delete_calls;
    init_calls = s_tex_init_calls;
    failed_state_is_empty();
    /* The table is allocated before the texture, so this failure creates no
     * texture and must not delete one. */
    assert(s_tex_init_calls == init_calls);
    assert(s_delete_calls == deletes);
    s_fail_table_malloc = false;
    assert(kj_wideart_init());
    kj_wideart_exit();

    valid_blob();
    assert(kj_wideart_init());
    deletes = s_delete_calls;
    kj_wideart_exit();
    kj_wideart_exit();
    assert(s_delete_calls == deletes + 1u);
    assert(kj_wideart_count() == 0);
    assert(kj_wideart_texture() == NULL);

    puts("PASS wide art: a failed init leaves no pictures and reload works");
    return 0;
}
"""


def main():
    cc = os.environ.get("CC", "gcc")
    source = (ROOT / "src/graphics/g2d/wideart.c").as_posix()
    with tempfile.TemporaryDirectory(prefix="kohjoh-wideart-") as tmp:
        tmp = Path(tmp)
        (tmp / "3ds.h").write_text(THREE_DS_H)
        (tmp / "citro3d.h").write_text(CITRO3D_H)
        harness = tmp / "wideart_test.c"
        harness.write_text(TEST_C)
        flags = [
            cc, "-std=gnu11", "-O2", "-Wall", "-Wextra",
            "-I", tmp.as_posix(), "-I", (ROOT / "src").as_posix(),
        ]
        module_obj = tmp / "wideart.o"
        subprocess.run([*flags, "-Dmalloc=test_malloc", "-c", source, "-o", module_obj.as_posix()],
                       cwd=ROOT, check=True)
        harness_obj = tmp / "wideart_test.o"
        subprocess.run([*flags, "-c", harness.as_posix(), "-o", harness_obj.as_posix()],
                       cwd=ROOT, check=True)
        exe = tmp / "wideart_test.exe"
        subprocess.run([cc, module_obj.as_posix(), harness_obj.as_posix(), "-o", exe.as_posix()],
                       cwd=ROOT, check=True)
        subprocess.run([exe.as_posix()], cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
